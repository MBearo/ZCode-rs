fn bmp(c: char) -> Option<u16> {
    u16::try_from(u32::from(c)).ok()
}

fn in_table(table: &[(u16, u16)], u: u16) -> bool {
    // 区间按起点升序：找最后一个起点 ≤ u 的区间。
    let k = table.partition_point(|&(lo, _)| lo <= u);
    k > 0 && table[k - 1].1 >= u
}

/// Java `Character.isLetter(char)`。
pub(crate) fn is_letter(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_alphabetic();
    }
    bmp(c).is_some_and(|u| in_table(&LETTERS, u))
}

/// Java `Character.isDigit(char)`：只认 Nd。
pub(crate) fn is_digit(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_digit();
    }
    bmp(c).is_some_and(|u| in_table(&DIGITS, u))
}

/// 十进制数字的值（Java `Character.digit(c, 10)` 对 Nd 的结果）；不是数字时为 `None`。
pub(crate) fn digit_value(c: char) -> Option<u32> {
    let u = bmp(c)?;
    let k = DIGITS.partition_point(|&(lo, _)| lo <= u);
    if k == 0 {
        return None;
    }
    let (lo, hi) = DIGITS[k - 1];
    (u <= hi).then(|| u32::from(u - lo))
}

/// Java `Character.isLetterOrDigit(char)`。
pub(crate) fn is_letter_or_digit(c: char) -> bool {
    is_letter(c) || is_digit(c)
}

/// Java `Character.isUpperCase(char)`：Lu 与 Other_Uppercase，与 Rust 的 `is_uppercase` 同义；BMP 之外是代理项，不是大写。
pub(crate) fn is_upper(c: char) -> bool {
    bmp(c).is_some() && c.is_uppercase()
}

/// Java `Character.isWhitespace(char)`：空格类分隔符（不含不断行的 U+00A0、U+2007、U+202F）、行与段分隔符，
/// 以及 `\t`、`\n`、U+000B、`\f`、`\r`、U+001C..U+001F。
pub(crate) fn is_whitespace(c: char) -> bool {
    matches!(
        c,
        '\t' | '\n' | '\u{000B}' | '\u{000C}' | '\r' | '\u{001C}'..='\u{001F}' | ' ' | '\u{1680}'
            | '\u{2000}'..='\u{2006}' | '\u{2008}'..='\u{200A}' | '\u{2028}' | '\u{2029}' | '\u{205F}' | '\u{3000}'
    )
}

/// Java `String.trim` 去掉的字符：码点 ≤ U+0020。
pub(crate) fn is_trim(c: char) -> bool {
    c <= ' '
}

/// Java 正则的 `\s`：`[ \t\n\x0B\f\r]`（Scala.js 1.7 起按 Java 的语义）。
pub(crate) fn is_regex_space(c: char) -> bool {
    matches!(c, ' ' | '\t' | '\n' | '\u{000B}' | '\u{000C}' | '\r')
}

/// Java 的 `s.trim`。
pub(crate) fn trim(s: &str) -> &str {
    s.trim_matches(is_trim)
}

/// `s.replaceAll("\\s+$", "")`：去掉行尾的 `\s`。
pub(crate) fn trim_end_space(s: &str) -> &str {
    s.trim_end_matches(is_regex_space)
}
