// Linux 交叉编译的 target、环境变量、包装脚本与 cargo 参数（docs/specs/rust-cli/linux.md §3）。纯函数。

import { BINARY_NAME } from "../binary.mjs";

/** 发布的两个 target：zig 的目标写法与 ELF 的 `e_machine`。 */
export const TARGETS = {
  "x86_64-unknown-linux-musl": { zig: "x86_64-linux-musl", machine: 62 },
  "aarch64-unknown-linux-musl": { zig: "aarch64-linux-musl", machine: 183 },
};

/**
 * `build-linux.mjs [--target <triple>]… [--clippy] [--debug]`；没有 `--target` 时是全部 target。`--debug`：dev 构建（不动
 * `build-number`，版本同本机的 debug 构建），给 SSH 的 Docker 测试上传（docs/specs/rust-cli/remote-exec.md §19.12）。
 */
export function parseCli(argv) {
  const targets = [];
  let clippy = false;
  let debug = false;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--clippy") {
      clippy = true;
    } else if (arg === "--debug") {
      debug = true;
    } else if (arg === "--target") {
      const triple = argv[i + 1];
      if (!triple) throw new Error("--target 后面要写 target");
      if (!TARGETS[triple]) {
        throw new Error(`不支持的 target ${triple}；可选：${Object.keys(TARGETS).join("、")}`);
      }
      if (!targets.includes(triple)) targets.push(triple);
      i += 1;
    } else {
      throw new Error(
        `不认识的参数 ${arg}；用法：build-linux.mjs [--target <triple>]… [--clippy] [--debug]`,
      );
    }
  }
  if (clippy && debug) throw new Error("--debug 不能和 --clippy 一起用");
  return { targets: targets.length ? targets : Object.keys(TARGETS), clippy, debug };
}

/**
 * cc-rs 与 cargo 按 target 读的环境变量：C 编译器、归档器、链接器、C 的编译选项；zig 的缓存放在 target 目录，
 * 不写到用户目录，`cargo clean` 一起删掉。`MI_LIBC_MUSL=1` 是 mimalloc 在 musl 上的构建开关（它的 CMake 选项，
 * libmimalloc-sys 的 build.rs 不设；linux.md §8.3）；别的 C 代码（ring、SQLite）不认这个宏。
 * C++（内嵌的 ugrep，embedded-search.md §7.2）：编译器是 `zig c++`，标准库是 zig 自带的静态 libc++（`CXXSTDLIB` =
 * `c++`，cc-rs 据此让 rustc 链接 `-lc++`）。
 */
export function cargoEnv({ triple, cc, cxx, ar, cache }) {
  const lower = triple.replaceAll("-", "_");
  return {
    [`CC_${lower}`]: cc,
    [`CXX_${lower}`]: cxx,
    [`CXXSTDLIB_${lower}`]: "c++",
    [`AR_${lower}`]: ar,
    [`CARGO_TARGET_${lower.toUpperCase()}_LINKER`]: cc,
    [`CFLAGS_${lower}`]: "-DMI_LIBC_MUSL=1",
    ZIG_GLOBAL_CACHE_DIR: cache,
    ZIG_LOCAL_CACHE_DIR: cache,
  };
}

/**
 * 去掉二进制里的本机路径（linux.md §3.2）：依赖 crate 的源码在 CARGO_HOME 下，装了 rust-src 时标准库的路径
 * 是本地源码；后者换成官方标准库的写法 `/rustc/<commit>`。
 */
export function remapFlags({ cargoHome, sysroot, commit }) {
  return [
    `--remap-path-prefix=${cargoHome}=/cargo`,
    `--remap-path-prefix=${sysroot}/lib/rustlib/src/rust=/rustc/${commit}`,
  ];
}

/** `cargo --config` 的 TOML：`target.<triple>.rustflags` 是字符串数组（JSON 的字符串转义也是合法的 TOML）。 */
export function rustflagsConfig(triple, flags) {
  return `target.${triple}.rustflags=[${flags.map((flag) => JSON.stringify(flag)).join(", ")}]`;
}

export function cargoArgs({ triple, clippy, debug = false, manifest, config }) {
  // debug 构建不带调试信息：只用来上传到测试容器，几百 MiB 的调试信息只会拖慢上传（remote-exec.md §19.12）。
  const common = [
    "--target",
    triple,
    "--config",
    config,
    ...(debug ? ["--config", "profile.dev.debug=0"] : []),
  ];
  return clippy
    ? [
        "clippy",
        "--locked",
        "--manifest-path",
        manifest,
        "--workspace",
        "--all-targets",
        ...common,
        "--",
        "-D",
        "warnings",
      ]
    : [
        "build",
        "--locked",
        ...(debug ? [] : ["--release"]),
        "--manifest-path",
        manifest,
        "-p",
        "rust-cli",
        "--bin",
        BINARY_NAME,
        ...common,
      ];
}

const shQuote = (text) => `'${text.replaceAll("'", "'\\''")}'`;

/**
 * cc-rs 与 cargo 调用的包装脚本：只转给 `node zig-tool.mjs <zig> <cc|ar> <zig 目标>`。Unix 上是 sh，
 * Windows 上是 .cmd（注释只用 ASCII：cmd.exe 按本地代码页读）。
 */
export function launcher({ windows, node, script, zig, tool, zigTarget }) {
  if (windows) {
    return {
      name: `${tool}.cmd`,
      text:
        "@rem Generated by scripts/rust-cli/build-linux.mjs (docs/specs/rust-cli/linux.md). Do not edit.\r\n" +
        `@"${node}" "${script}" "${zig}" ${tool} ${zigTarget} %*\r\n`,
    };
  }
  return {
    name: tool,
    text:
      "#!/bin/sh\n" +
      "# 由 scripts/rust-cli/build-linux.mjs 生成（docs/specs/rust-cli/linux.md §3），不要手改。\n" +
      `exec ${shQuote(node)} ${shQuote(script)} ${shQuote(zig)} ${tool} ${zigTarget} "$@"\n`,
  };
}
